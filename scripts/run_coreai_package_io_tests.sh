#!/usr/bin/env bash
set -euo pipefail

# Execute the real Foundation/Darwin implementation without any model assets,
# app signing, Core AI framework or third-party Swift package dependencies.
# Only inference-service collaborators are doubled; filesystem, configuration,
# publication, recovery, cancellation bus and operation ownership use app source.
if [[ "$(uname -s)" != "Darwin" ]]; then
  printf 'Core AI package IO tests require macOS and a Swift 6.2+ toolchain.\n' >&2
  exit 2
fi
command -v swift >/dev/null 2>&1 || { printf 'swift is unavailable.\n' >&2; exit 2; }

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PACKAGE_DIR="$(mktemp -d "${TMPDIR:-/tmp}/lumen-coreai-package-io.XXXXXX")"
trap 'rm -rf "$PACKAGE_DIR"' EXIT
mkdir -p "$PACKAGE_DIR/Sources/Lumen" "$PACKAGE_DIR/Tests/LumenTests"
# Foundation may canonicalize /var into /private/var when enumerating on macOS.
# Give all fixtures a canonical root so an alias cannot masquerade as a path
# containment failure in either historical or current implementations.
mkdir -p "$PACKAGE_DIR/fixtures"
export TMPDIR="$(cd "$PACKAGE_DIR/fixtures" && pwd -P)/"
for source in \
  ios/Lumen/Services/LLM/CoreAILocalPackageIO.swift \
  ios/Lumen/Services/LLM/CoreAIModelInstallationRecovery.swift \
  ios/Lumen/Services/LLM/CoreAIGemmaModelStore.swift \
  ios/Lumen/Services/LLM/CoreAITextEmbeddingModelStore.swift \
  ios/Lumen/Services/LLM/CoreAI/CoreAITextEmbeddingPolicy.swift \
  ios/Lumen/System/AppCancellationBus.swift \
  ios/Lumen/System/ModelSettingsOperationOwner.swift \
  ios/Lumen/Views/CoreAIGemmaSettingsSection.swift \
  ios/LumenTests/Support/CoreAIPackageIOHarnessSupport.swift; do
  cp "$ROOT_DIR/$source" "$PACKAGE_DIR/Sources/Lumen/"
done
for test in \
  CoreAILocalPackageIOTests.swift \
  CoreAIGemmaModelStoreTests.swift \
  CoreAITextEmbeddingModelStoreTests.swift \
  CoreAIModelStoreRecoveryTests.swift \
  CoreAIModelReplacementLifecycleTests.swift \
  NativeModelLoadCancellationTests.swift \
  ModelSettingsOperationOwnerTests.swift; do
  cp "$ROOT_DIR/ios/LumenTests/$test" "$PACKAGE_DIR/Tests/LumenTests/"
done
# Compile the exact synchronous ModelLoader entry point with pending legacy
# metadata and runtime actors doubled. The app's whole loader depends on UIKit
# and its scene/model graph; this checks immediate bus cancellation, not loading.
python3 - "$ROOT_DIR" "$PACKAGE_DIR/Sources/Lumen/ModelLoaderCancellation.swift" <<'PYTHON'
from pathlib import Path
import sys

source = (Path(sys.argv[1]) / "ios/Lumen/Services/ModelLoader.swift").read_text(encoding="utf-8")
signature = "    static func cancelActiveLoads() {"
assert source.count(signature) == 1, "ModelLoader cancellation entry point is ambiguous"
start = source.index(signature)
end = source.index("\n    }\n", start) + len("\n    }")
method = source[start:end]
header = """import Foundation
// Generated by the native regression runner from the unmodified app method.
// Only this method body is production code; collaborators below are doubles.
@MainActor enum ModelLoader {
    struct PendingLoad { let task: Task<Bool, Never> }
    static var chatLoadTask: PendingLoad?
    static var embedLoadTask: PendingLoad?
    static func advanceChatLoadEpoch() {}
    static func advanceEmbedLoadEpoch() {}
    static func finishChatLoad(_ pending: PendingLoad) async -> Bool { false }
    static func finishEmbedLoad(_ pending: PendingLoad) async -> Bool { false }
"""
Path(sys.argv[2]).write_text(header + method + "\n}\n", encoding="utf-8")
PYTHON
cat > "$PACKAGE_DIR/Package.swift" <<'SWIFT'
// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "CoreAILocalPackageIORegression",
    platforms: [.macOS(.v15)],
    products: [.library(name: "Lumen", targets: ["Lumen"])],
    targets: [
        .target(name: "Lumen"),
        .testTarget(name: "LumenTests", dependencies: ["Lumen"])
    ],
    swiftLanguageModes: [.v5]
)
SWIFT

swift test --package-path "$PACKAGE_DIR" -c release \
  -Xswiftc -DCOREAI_PACKAGE_IO_MEMORY_TESTS \
  -Xswiftc -enable-upcoming-feature -Xswiftc MemberImportVisibility \
  --filter '(CoreAI(LocalPackageIO|GemmaModelStore|TextEmbeddingModelStore|ModelStoreRecovery|ModelReplacementLifecycle)|ModelSettingsOperationOwner|NativeModelLoadCancellation)Tests'
