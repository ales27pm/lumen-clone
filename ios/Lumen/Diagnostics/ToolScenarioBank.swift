    private static func stableID(_ parts: String...) -> String {
        let raw = parts.joined(separator: "|").lowercased()
        let safe = raw.map { ch in
            (ch.isLetter || ch.isNumber) ? ch : "-"
        }
        let collapsed = String(safe).split(separator: "-").joined(separator: "-")
        return String(collapsed.prefix(96))
    }
