import Foundation

nonisolated struct ToolScenarioBankEntry: Codable, Sendable, Identifiable, Hashable {
    enum ScenarioKind: String, Codable, Sendable, CaseIterable {
        case direct
        case alternatePhrasing
        case missingArgument
        case clarification
        case approvalBoundary
        case regression
    }

    let id: String
    let toolID: String
    let title: String
    let prompt: String
    let kind: ScenarioKind
    let expectedIntent: String?
    let expectedToolID: String
    let requiredSlots: [AgentWorkflowSlot]
    let datasetUse: String
    let notes: String
}

nonisolated struct ToolScenarioCoverageSummary: Codable, Sendable, Equatable {
    let toolCount: Int
    let scenarioCount: Int
    let toolsWithAtLeastThreeScenarios: Int
    let missingToolIDs: [String]
    let requiredSlotCounts: [String: Int]

    var isProductionReady: Bool {
        missingToolIDs.isEmpty && toolsWithAtLeastThreeScenarios == toolCount
    }
}

nonisolated enum ToolScenarioBank {
    static let minimumScenariosPerTool = 3
    private static let sampleUUID = "00000000-0000-0000-0000-000000000000"

    static func entries(tools: [ToolDefinition] = ToolRegistry.all) -> [ToolScenarioBankEntry] {
        tools.flatMap { scenarios(for: $0) }
            .sorted { lhs, rhs in
                if lhs.toolID == rhs.toolID { return lhs.id < rhs.id }
                return lhs.toolID < rhs.toolID
            }
    }

    static func entriesByTool(tools: [ToolDefinition] = ToolRegistry.all) -> [String: [ToolScenarioBankEntry]] {
        Dictionary(grouping: entries(tools: tools), by: \ToolScenarioBankEntry.toolID)
    }

    static func coverageSummary(tools: [ToolDefinition] = ToolRegistry.all) -> ToolScenarioCoverageSummary {
        let allEntries = entries(tools: tools)
        let grouped = Dictionary(grouping: allEntries, by: \ToolScenarioBankEntry.toolID)
        let expectedIDs = Set(tools.map { ToolRouteGuard.canonicalToolID($0.id) })
        let missing = expectedIDs
            .filter { (grouped[$0]?.count ?? 0) < minimumScenariosPerTool }
            .sorted()
        var slotCounts: [String: Int] = [:]
        for entry in allEntries {
            for slot in entry.requiredSlots {
                slotCounts[slot.rawValue, default: 0] += 1
            }
        }
        return ToolScenarioCoverageSummary(
            toolCount: expectedIDs.count,
            scenarioCount: allEntries.count,
            toolsWithAtLeastThreeScenarios: expectedIDs.count - missing.count,
            missingToolIDs: missing,
            requiredSlotCounts: slotCounts
        )
    }

    static func scenarios(for tool: ToolDefinition) -> [ToolScenarioBankEntry] {
        let toolID = ToolRouteGuard.canonicalToolID(tool.id)
        let intent = inferredIntent(for: toolID)
        let requiresApproval = ToolRouteGuard.requiresUserApproval(toolID) || tool.requiresApproval
        let baseSlots = requiredSlots(for: toolID, requiresApproval: requiresApproval)

        var entries: [ToolScenarioBankEntry] = []
        entries.append(entry(
            toolID: toolID,
            title: "Direct \(tool.name)",
            prompt: directPrompt(for: toolID, name: tool.name),
            kind: .direct,
            expectedIntent: intent,
            requiredSlots: baseSlots,
            datasetUse: "must_pass_e2e"
        ))
        entries.append(entry(
            toolID: toolID,
            title: "Alternate phrasing \(tool.name)",
            prompt: alternatePrompt(for: toolID, name: tool.name),
            kind: .alternatePhrasing,
            expectedIntent: intent,
            requiredSlots: baseSlots,
            datasetUse: "routing_variation"
        ))
        entries.append(entry(
            toolID: toolID,
            title: requiresApproval ? "Approval boundary \(tool.name)" : "Missing argument \(tool.name)",
            prompt: requiresApproval ? approvalPrompt(for: toolID, name: tool.name) : missingArgumentPrompt(for: toolID, name: tool.name),
            kind: requiresApproval ? .approvalBoundary : .missingArgument,
            expectedIntent: intent,
            requiredSlots: baseSlots,
            datasetUse: requiresApproval ? "approval_boundary" : "clarification_or_repair"
        ))
        return entries
    }

    private static func entry(
        toolID: String,
        title: String,
        prompt: String,
        kind: ToolScenarioBankEntry.ScenarioKind,
        expectedIntent: String?,
        requiredSlots: [AgentWorkflowSlot],
        datasetUse: String,
        notes: String = "Generated by Control Tower scenario bank."
    ) -> ToolScenarioBankEntry {
        ToolScenarioBankEntry(
            id: stableID(toolID, kind.rawValue, prompt),
            toolID: toolID,
            title: title,
            prompt: prompt,
            kind: kind,
            expectedIntent: expectedIntent,
            expectedToolID: toolID,
            requiredSlots: requiredSlots,
            datasetUse: datasetUse,
            notes: notes
        )
    }

    private static func requiredSlots(for toolID: String, requiresApproval: Bool) -> [AgentWorkflowSlot] {
        var slots: [AgentWorkflowSlot] = [.cortex, .executor]
        if toolID.hasPrefix("memory.") || toolID.hasPrefix("rag.") || toolID.hasPrefix("files.") {
            slots.append(.rem)
            slots.append(.embedding)
        }
        if requiresApproval {
            slots.append(.mimicry)
        }
        slots.append(.mouth)
        return Array(NSOrderedSet(array: slots).compactMap { $0 as? AgentWorkflowSlot })
    }

    private static func inferredIntent(for toolID: String) -> String? {
        if toolID == "weather" { return UserIntent.weather.rawValue }
        if toolID.hasPrefix("web.") { return UserIntent.webSearch.rawValue }
        if toolID.hasPrefix("memory.") { return UserIntent.memory.rawValue }
        if toolID.hasPrefix("rag.") { return UserIntent.rag.rawValue }
        if toolID.hasPrefix("files.") { return UserIntent.files.rawValue }
        if toolID.hasPrefix("outlook.") { return UserIntent.outlook.rawValue }
        if toolID.hasPrefix("mail.") { return UserIntent.emailDraft.rawValue }
        if toolID.hasPrefix("messages.") { return UserIntent.messageDraft.rawValue }
        if toolID.hasPrefix("maps.") || toolID == "location.current" { return UserIntent.maps.rawValue }
        if toolID.hasPrefix("calendar.") { return UserIntent.calendar.rawValue }
        if toolID.hasPrefix("reminders.") { return UserIntent.reminder.rawValue }
        if toolID.hasPrefix("alarm.") { return UserIntent.alarm.rawValue }
        if toolID.hasPrefix("trigger.") { return UserIntent.trigger.rawValue }
        if toolID == "phone.call" { return UserIntent.phoneCall.rawValue }
        if toolID.hasPrefix("contacts.") { return UserIntent.contactSearch.rawValue }
        if toolID.hasPrefix("photos.") { return UserIntent.photos.rawValue }
        if toolID == "camera.capture" { return UserIntent.camera.rawValue }
        if toolID == "health.summary" { return UserIntent.health.rawValue }
        if toolID == "motion.activity" { return UserIntent.motion.rawValue }
        return nil
    }

